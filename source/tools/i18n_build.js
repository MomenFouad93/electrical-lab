/* Build src/i18n_data.js from i18n/keys.json + i18n/work/*.txt.  Usage: node tools/i18n_build.js [--check] */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const LANGS = ['fr', 'pt', 'zh', 'ru', 'pl', 'hu', 'es'];
const keys = JSON.parse(fs.readFileSync(path.join(root, 'i18n/keys.json'), 'utf8'));
const byId = new Map(keys.map((k) => [k.id, k]));
const dir = path.join(root, 'i18n/work');
const tr = new Map(); // id -> [7]
const problems = [];
for (const f of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
  if (!/\.txt$/.test(f)) continue;
  const blocks = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r/g, '').split(/\n\s*\n/);
  for (const b of blocks) {
    const lines = b.split('\n'); while (lines.length && !lines[0].trim()) lines.shift();
    if (!lines.length) continue;
    const m = /^#(\d+)\s*$/.exec(lines[0]);
    if (!m) { problems.push(f + ': bad block header: ' + lines[0].slice(0, 40)); continue; }
    while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
    const id = +m[1], rest = lines.slice(1);
    if (!byId.has(id)) { problems.push(f + ': unknown id ' + id); continue; }
    if (rest.length !== 7) { problems.push(f + ' #' + id + ': ' + rest.length + ' lines (need 7)'); continue; }
    tr.set(id, rest.map((x) => x.replace(/\\n/g, '\n')));
  }
}
/* validation */
const nums = (s0, lenient) => { const s = s0.replace(/[\u2013\u2014]/g, '-'); return (((lenient ? s.replace(/(?<![\d.,\-])\d(?![\d.,]|-\d)/g, '') : s)).match(/\d+(?:[.,]\d+)?/g) || []).map((x) => x.replace(',', '.')).sort().join('|'); };
const LEN = (en) => /\b\d[- ]?(pole|phase|core|way|wire|position|channel|row)\b/i.test(en);
const toks = (s) => (s.match(/\{\d+\}/g) || []).sort().join('|');
const SCRIPT = { zh: /[一-鿿]/, ru: /[Ѐ-ӿ]/ };
for (const [id, arr] of tr) {
  const k = byId.get(id);
  arr.forEach((t, i) => {
    const L = LANGS[i];
    if (t === '=') return;
    if (!t.trim()) problems.push('#' + id + ' ' + L + ': empty');
    if (toks(t) !== toks(k.en)) problems.push('#' + id + ' ' + L + ': placeholders differ: ' + k.en.slice(0, 50));
    if (L !== 'zh' && nums(t, LEN(k.en)) !== nums(k.en, LEN(k.en)) && !/\b(one|two|three|four|five|six|seven|eight|nine|ten|twelve)\b/i.test(k.en)) problems.push('#' + id + ' ' + L + ': numbers differ [' + nums(k.en, true) + '] vs [' + nums(t, true) + '] ' + k.en.slice(0, 40));
    if (SCRIPT[L] && /[a-z]{4,}/i.test(k.en) && !SCRIPT[L].test(t)) problems.push('#' + id + ' ' + L + ': wrong script: ' + t.slice(0, 40));
    if (/[؀-ۿ]/.test(t)) problems.push('#' + id + ' ' + L + ': contains Arabic letters');
  });
}
const done = [...tr.keys()];
const static_ = keys.filter((k) => !k.tpl), tpl_ = keys.filter((k) => k.tpl);
const missing = static_.filter((k) => !tr.has(k.id)).length, missingT = tpl_.filter((k) => !tr.has(k.id)).length;
console.log('translated', done.length, '| missing static', missing, '| missing templates', missingT, '| problems', problems.length);
if (problems.length) console.log(problems.slice(0, +process.env.MAXP || 40).join('\n'));
if (process.argv.includes('--check')) process.exit(0);
const D = { keys: [], tpl: [] };
for (const L of LANGS) D[L] = [];
for (const k of static_) {
  const a = tr.get(k.id); if (!a) continue;
  D.keys.push(k.en);
  LANGS.forEach((L, i) => D[L].push(a[i] === '=' ? '' : a[i]));
}
for (const k of tpl_) {
  const a = tr.get(k.id); if (!a) continue;
  const o = { en: k.en }; LANGS.forEach((L, i) => { if (a[i] !== '=') o[L] = a[i]; }); D.tpl.push(o);
}
fs.writeFileSync(path.join(root, 'src/i18n_data.js'), '/* generated by tools/i18n_build.js */\n(function (g) { g.EL = g.EL || {}; g.EL.I18N = ' + JSON.stringify(D) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n');
console.log('wrote src/i18n_data.js', (fs.statSync(path.join(root, 'src/i18n_data.js')).size / 1024).toFixed(0) + ' KB');
